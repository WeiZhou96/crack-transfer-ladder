# -*- coding: utf-8 -*-
"""Quadruplet assembly.

A group is (x₀₀, x₀₁, x₁₀, x₁₁), indexed by (crack c, distractor e). A group strictly shares: the background crop B,
the brush transmittance field R and mask M (the brush is computed once and reused from cache = paired RNG), the
distractor parameters θ_z (including the seed, hence identical geometry), and the acquisition parameters θ_ν
(including the noise seed).
Rendering order follows the operator slot:
  S_pre operators (joint / repair_boundary): pre₀₁ = Z(B), pre₁₁ = P(Z(B)) -- the distractor lies beneath the crack;
  L_light operators (shadow)              : pre₁₀ = P(B), pre₁₁ = Z(P(B)) -- the shadow is applied after the brush;
  final layer xₖ = A_ν(preₖ), with the same θ_ν for all four images.
Labels: y₀₀ = y₀₁ = 0; y₁₀ = y₁₁ = M ⊙ V, ignore = M ⊙ ¬V. V uses the paired definition
      (visibility.visibility_mask_paired): the signed contrast difference ΔC along the skeleton of M, x₁₀ against x₀₀
      and x₁₁ against x₀₁. τ_Δ requires human calibration, so rendering stores only the skeleton point coordinates
      and ΔC (dc.npz); V/ignore are generated by labels_from_dc once τ_Δ is fixed, without re-rendering.
Crack contrast α: R ← R^α; α=1 keeps the source contrast; α<1 pulls the transmittance towards 1 and fades the crack,
      so that the "hard but visible" band is adequately represented. The α distribution is a default
      (configs/operators.yaml quadruplet.contrast_alpha); once τ_Δ is fixed it should become stratified sampling
      around τ_Δ.
Spatial relation r (linear distractors: joint, linear shadow): the target d bin is drawn uniformly from
      {overlap, near, far}; a distractor centreline position is proposed for that bin and accepted only if
      relation.measure confirms it (rejection sampling). Δφ and n are recorded but not stratified (default).
      If the target bin is unreachable (e.g. near is geometrically impossible for a wide joint and a thin crack),
      the remaining bins are tried and recorded in r_fallback.
Reproducibility: the spec (JSON) contains every choice and seed, so render_group(spec) is pixel-deterministic; the
manifest records the sha256 of every output PNG.
"""
from __future__ import annotations

import csv
import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

from . import brush
from .operators import OPERATORS, Context, PreconditionError, relation
from .operators import acquisition
from .operators.base import line_coordinates, skeletonize_mask
from .operators.visibility import _propagate, signed_contrast_on_skeleton

SCHEMA = "crackcf-quadruplet-1"
STRATA = {"laser_asphalt": ("laser_gray", "asphalt"), "rgb_asphalt": ("rgb_photo", "asphalt"),
          "rgb_concrete": ("rgb_photo", "concrete")}
LAYERS = ("x00", "x01", "x10", "x11")
# crack polarity per stratum: laser line-scan frames show cracks as BRIGHT lines (on PaveDistress samples the
# centreline is ~40% brighter than the surrounding ring), photos show them dark.
POLARITY = {"laser_asphalt": "bright", "rgb_asphalt": "dark", "rgb_concrete": "dark"}


@dataclass
class Resources:
    data_root: Path
    domains: dict
    registry: dict                     # image_id -> registry row
    pools: dict                        # stratum -> [candidate rows]
    library: dict                      # material -> [instance rows]
    library_by_id: dict
    _field_cache: dict = field(default_factory=dict)

    def brush_field(self, instance_id: str) -> brush.BrushField:
        if instance_id not in self._field_cache:
            inst = self.library_by_id[instance_id]
            crop = np.asarray(Image.open(self.data_root / "mask_library/v2" / inst["mask_crop"]).convert("L")) > 0
            self._field_cache[instance_id] = brush.extract_field(inst["source_path"], inst["source_mask_path"],
                                                                 inst["bbox_xyxy"], crop)
        return self._field_cache[instance_id]


def load_resources(data_root: Path, domains: dict, pool_csv: Path, watermark_csv: Path) -> Resources:
    registry = {}
    for line in open(data_root / "registry/registry.jsonl", encoding="utf-8"):
        row = json.loads(line)
        registry[row["image_id"]] = row
    pools = {name: [] for name in STRATA}
    for c in csv.DictReader(open(pool_csv, encoding="utf-8")):
        if c["surface"] == "structure":
            continue
        for name, (dom, mat) in STRATA.items():
            if c["domain"] == dom and c["material"] == mat:
                pools[name].append(c)
    watermark_ok = {r["image_id"] for r in csv.DictReader(open(watermark_csv, encoding="utf-8"))
                    if r["overlay_final"] == "no"}
    library, by_id = {"asphalt": [], "concrete": []}, {}
    for line in open(data_root / "mask_library/v2/instances.jsonl", encoding="utf-8"):
        inst = json.loads(line)
        if inst["material_pool"] not in library or inst["skel_len_px"] < 30:
            continue
        if inst["source_dataset"] == "deepcrack" and inst["image_id"] not in watermark_ok:
            continue                                   # source filtering: images with watermarks/overlays are not texture sources
        library[inst["material_pool"]].append(inst)
        by_id[inst["instance_id"]] = inst
    return Resources(data_root, domains, registry, pools, library, by_id)


# ---------------------------------------------------------------- sampling

def _crack_skel_len(res: Resources, instance_id: str) -> float:
    return float(res.library_by_id[instance_id]["skel_len_px"])


def _sample_crack(rng, res: Resources, material: str, bg_image: str, side: int) -> dict:
    cands = res.library[material]
    for _ in range(50):
        inst = cands[int(rng.integers(len(cands)))]
        if inst["image_id"] == bg_image:
            continue
        f = res.brush_field(inst["instance_id"])
        for _ in range(30):
            k = int(rng.integers(8))
            h, w = brush.dihedral(f.mask, k).shape
            ox = int(rng.integers(-w + 1, side))
            oy = int(rng.integers(-h + 1, side))
            M, _ = brush.place(f, k, ox, oy, (side, side))
            ok, info = brush.placement_ok(M, _crack_skel_len(res, inst["instance_id"]), side)
            if ok:
                return {"instance_id": inst["instance_id"], "image_id": inst["image_id"],
                        "source_dataset": inst["source_dataset"], "dihedral": k, "ox": ox, "oy": oy, **info}
    raise RuntimeError("no placeable crack instance found")


def _line_param(op: str, theta: dict) -> tuple[float, str]:
    if op == "joint":
        return theta["angle_deg"], "offsets_px"
    return theta["line_angle_deg"], "line_offset_px"


def _propose_line(rng, op: str, theta: dict, target: str, M: np.ndarray, side: int) -> dict:
    theta = dict(theta)
    angle, key = _line_param(op, theta)
    s0, _ = line_coordinates((side, side), angle, 0.0)
    skel = skeletonize_mask(M > 0)
    svals = s0[skel > 0]
    half = (theta["width_px"] / 2.0 + max(1.0, theta["width_px"] / 4.0) + 1.0) if op == "joint" \
        else theta["line_width_px"] / 2.0 + theta["penumbra_px"]
    lim = 0.5 * side * 1.3
    if target == "overlap":
        o = float(rng.choice(svals)) + float(rng.uniform(-half, half))
    elif target == "near":
        o = float(rng.choice(svals)) + float(rng.choice([-1, 1])) * (half + float(rng.uniform(0.5, 6.0)))
    else:
        o = float(rng.uniform(-lim, lim))
    if op == "joint":
        offsets = [o]
        if theta["n_joints"] == 2:
            extent = side * (abs(np.cos(np.deg2rad(angle))) + abs(np.sin(np.deg2rad(angle))))
            o2 = o + float(rng.choice([-1, 1])) * float(rng.uniform(0.3, 0.8)) * extent
            if abs(o2) < extent / 2 - theta["width_px"]:
                offsets.append(o2)
        theta["offsets_px"] = [round(v, 3) for v in sorted(offsets)]
        theta["n_joints"] = len(offsets)
    else:
        theta["line_offset_px"] = o
    return theta


def _is_linear(op: str, theta: dict) -> bool:
    return op == "joint" or (op == "shadow" and theta.get("kind") == "linear")


def sample_spec(rng: np.random.Generator, op: str, index: int, res: Resources) -> dict:
    qcfg = res.domains["quadruplet"]
    weights = qcfg["stratum_weights"][op]
    allowed = res.domains[op].get("domains")           # typed precondition on the imaging domain (e.g. shadow)
    names = [n for n in weights if res.pools[n] and (allowed is None or STRATA[n][0] in allowed)]
    probs = np.array([weights[n] for n in names], float)
    stratum = names[int(rng.choice(len(names), p=probs / probs.sum()))]
    domain, material = STRATA[stratum]
    pool = res.pools[stratum]
    bg = pool[int(rng.integers(len(pool)))]
    side = int(bg["side"])
    ctx = Context(material=material)
    module = OPERATORS[op]
    spec = {"schema": SCHEMA, "group_id": f"{op}_{index:05d}", "operator": op, "slot": res.domains[op]["slot"],
            "stratum": stratum,
            "background": {k: bg[k] for k in ("crop_id", "image_id", "source_dataset", "group_id", "domain",
                                               "material", "x", "y", "side")}}
    fallback = []
    for attempt in range(6):
        crack = _sample_crack(rng, res, material, bg["image_id"], side)
        f = res.brush_field(crack["instance_id"])
        M, _ = brush.place(f, crack["dihedral"], crack["ox"], crack["oy"], (side, side))
        theta = module.sample_theta(rng, ctx, res.domains[op], (side, side))
        if not _is_linear(op, theta):
            spec.update(crack=crack, theta_z=theta, r_target=None)
            break
        targets = list(qcfg["r_targets"])
        target = targets[int(rng.integers(len(targets)))]
        order = [target] + [t for t in targets if t != target]
        found = None
        for t in order:
            for _ in range(qcfg["max_r_tries"]):
                base = module.sample_theta(rng, ctx, res.domains[op], (side, side))
                while not _is_linear(op, base):          # keep the linear type (the shadow kind is set by the first draw)
                    base = module.sample_theta(rng, ctx, res.domains[op], (side, side))
                cand = _propose_line(rng, op, base, t, M, side)
                result = module.render(np.zeros((side, side, 3), np.float32) + 0.5, cand, ctx, res.domains[op])
                if result.centerline is None or not result.centerline.any():
                    continue
                r = relation.measure(result.centerline, result.omega, M)
                if r["d_bin"] == t:
                    found = (t, cand, r)
                    break
            if found:
                break
            fallback.append(t)
        if found:
            spec.update(crack=crack, theta_z=found[1], r_target=target, r_realized_bin=found[0],
                        r_fallback=fallback)
            break
    else:
        raise RuntimeError(f"{spec['group_id']}: no r bin is reachable")
    ca = qcfg.get("contrast_alpha")
    if ca is not None:                                 # crack contrast attenuation R^α (α=1 keeps the source contrast)
        if rng.random() < ca["natural_prob"]:
            alpha = 1.0
        else:
            lo, hi = ca["log_uniform"]
            alpha = float(np.exp(rng.uniform(np.log(lo), np.log(hi))))
        spec["crack"]["contrast_alpha"] = alpha
    spec["crack"]["polarity"] = POLARITY[stratum]
    spec["theta_nu"] = acquisition.sample_theta(rng, res.domains["acquisition"])
    return spec


# ---------------------------------------------------------------- rendering

def load_background(res: Resources, bg: dict) -> np.ndarray:
    x, y, s = int(bg["x"]), int(bg["y"]), int(bg["side"])
    with Image.open(res.registry[bg["image_id"]]["path"]) as im:
        crop = im.convert("RGB").crop((x, y, x + s, y + s))
    return np.asarray(crop, np.float32) / 255.0


def render_group(spec: dict, res: Resources) -> dict:
    op, module = spec["operator"], OPERATORS[spec["operator"]]
    ctx = Context(material=spec["background"]["material"])
    B = load_background(res, spec["background"])
    side = B.shape[0]
    c = spec["crack"]
    f = res.brush_field(c["instance_id"])
    M, R = brush.place(f, c["dihedral"], c["ox"], c["oy"], (side, side))
    alpha = c.get("contrast_alpha", 1.0)
    if alpha != 1.0:
        R = np.where(R != 1.0, np.power(R, alpha), 1.0).astype(np.float32)
    pol = c.get("polarity", "dark")                     # v1/v2 specs predate the polarity field -> dark
    dom = res.domains[op]
    allowed = dom.get("domains")
    if allowed is not None and "polarity" in c and spec["background"]["domain"] not in allowed:
        raise PreconditionError(f"{op}: imaging domain {spec['background']['domain']!r} not in {allowed}")
    pre = {"x00": B}
    if spec["slot"] == "S_pre":
        z = module.render(B, spec["theta_z"], ctx, dom)
        pre["x01"] = z.image
        pre["x10"], omega_m = brush.apply(B, R, pol)
        pre["x11"], _ = brush.apply(z.image, R, pol)
    elif spec["slot"] == "L_light":
        pre["x10"], omega_m = brush.apply(B, R, pol)
        z = module.render(B, spec["theta_z"], ctx, dom)
        pre["x01"] = z.image
        z11 = module.render(pre["x10"], spec["theta_z"], ctx, dom)
        if not np.array_equal(z11.omega, z.omega):
            raise AssertionError("the support of the same θ_z differs between the two layers")
        pre["x11"] = z11.image
    else:
        raise ValueError(f"unsupported slot {spec['slot']}")
    omega_z = z.omega

    def outside_max(a, b, region):
        d = np.abs(pre[a] - pre[b]).max(axis=2)
        return float(d[~region].max()) if (~region).any() else 0.0

    q2_pre = {"x01_vs_x00_outside_omega_z": outside_max("x01", "x00", omega_z),
              "x10_vs_x00_outside_omega_m": outside_max("x10", "x00", omega_m),
              "x11_vs_x01_outside_omega_m": outside_max("x11", "x01", omega_m),
              "x11_vs_x10_outside_omega_z": outside_max("x11", "x10", omega_z)}
    final = {k: acquisition.render(v, spec["theta_nu"]) for k, v in pre.items()}
    u8 = {k: (np.clip(v, 0, 1) * 255.0 + 0.5).astype(np.uint8) for k, v in final.items()}
    f8 = {k: v.astype(np.float32) / 255.0 for k, v in u8.items()}   # V is computed on the saved 8-bit images, matching what training sees
    win = res.domains["visibility_paired"]["window_px"]
    # bright-polarity cracks: the signed (dark-crack-positive) contrast is taken on the inverted image
    view = (lambda im: 1.0 - im) if pol == "bright" else (lambda im: im)
    c10, skel = signed_contrast_on_skeleton(view(f8["x10"]), M, win)
    c00, _ = signed_contrast_on_skeleton(view(f8["x00"]), M, win)
    c11, _ = signed_contrast_on_skeleton(view(f8["x11"]), M, win)
    c01, _ = signed_contrast_on_skeleton(view(f8["x01"]), M, win)
    ys, xs = np.nonzero(skel)
    dc10 = (c10 - c00)[ys, xs].astype(np.float32)
    dc11 = (c11 - c01)[ys, xs].astype(np.float32)
    measured = {"q2_pre_max_abs_outside": q2_pre, "operator": z.measured,
                "crack_px": int(M.sum()), "crack_skel_px": int(len(ys)),
                "crack_in_omega_z_frac": round(float((M.astype(bool) & omega_z).sum() / max(M.sum(), 1)), 5),
                "omega_z_frac": round(float(omega_z.mean()), 5), "omega_m_frac": round(float(omega_m.mean()), 5),
                "dc10_median": round(float(np.median(dc10)), 5), "dc11_median": round(float(np.median(dc11)), 5),
                "brush": f.stats}
    if _is_linear(op, spec["theta_z"]):
        measured["r"] = relation.measure(z.centerline, omega_z, M) if z.centerline is not None else None
    return {"images": u8, "M": M, "omega_z": omega_z, "omega_m": omega_m,
            "skel_yx": np.stack([ys, xs], 1).astype(np.int32), "dc10": dc10, "dc11": dc11, "measured": measured}


def labels_from_dc(M: np.ndarray, skel_yx: np.ndarray, dc: np.ndarray, tau_delta: float) -> tuple[np.ndarray, np.ndarray]:
    """Generate (y, ignore) for a fixed τ_Δ: V = 1[ΔC ≥ τ_Δ] on skeleton points, propagated to the whole mask via the nearest skeleton point."""
    crack = M > 0
    skel = np.zeros(M.shape, np.uint8)
    skel[skel_yx[:, 0], skel_yx[:, 1]] = 1
    vis = np.zeros(M.shape, bool)
    vis[skel_yx[:, 0], skel_yx[:, 1]] = dc >= tau_delta
    v = _propagate(crack, skel, vis)
    return (crack & v).astype(np.uint8), (crack & ~v).astype(np.uint8)


def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def encode_png(a: np.ndarray) -> bytes:
    arr = a[..., ::-1] if a.ndim == 3 else a
    ok, buf = cv2.imencode(".png", arr, [cv2.IMWRITE_PNG_COMPRESSION, 3])
    if not ok:
        raise RuntimeError("PNG encoding failed")
    return buf.tobytes()


def write_group(out_dir: Path, spec: dict, rendered: dict) -> dict:
    out_dir.mkdir(parents=True, exist_ok=False)
    files = {}
    blobs = {f"{k}.png": encode_png(v) for k, v in rendered["images"].items()}
    blobs["M.png"] = encode_png(rendered["M"] * 255)
    blobs["omega_z.png"] = encode_png(rendered["omega_z"].astype(np.uint8) * 255)
    blobs["omega_m.png"] = encode_png(rendered["omega_m"].astype(np.uint8) * 255)
    for name, b in blobs.items():
        (out_dir / name).write_bytes(b)
        files[name] = sha256_bytes(b)
    np.savez_compressed(out_dir / "dc.npz", skel_yx=rendered["skel_yx"], dc10=rendered["dc10"], dc11=rendered["dc11"])
    manifest = {"spec": spec, "measured": rendered["measured"], "files_sha256": files,
                "labels": {"y00": "zeros", "y01": "zeros", "y10_y11": "M ⊙ V(ΔC ≥ τ_Δ) via labels_from_dc",
                           "tau_delta": None, "tau_delta_status": "pending human calibration (kit v4)"}}
    (out_dir / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=1), encoding="utf-8")
    return manifest


def rerender_hashes(spec: dict, res: Resources) -> dict:
    r = render_group(spec, res)
    out = {f"{k}.png": sha256_bytes(encode_png(v)) for k, v in r["images"].items()}
    out["M.png"] = sha256_bytes(encode_png(r["M"] * 255))
    out["omega_z.png"] = sha256_bytes(encode_png(r["omega_z"].astype(np.uint8) * 255))
    out["omega_m.png"] = sha256_bytes(encode_png(r["omega_m"].astype(np.uint8) * 255))
    return out
